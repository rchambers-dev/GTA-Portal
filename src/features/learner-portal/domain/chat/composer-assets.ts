function giphyUrl(id: string, size: "giphy" | "200w" = "giphy"): string {
  return `https://media.giphy.com/media/${id}/${size}.gif`;
}

export type ChatGifOption = ChatGifAttachment & {
  id: string;
  tags: string[];
};

export const CHAT_GIF_CATALOG: ChatGifOption[] = GIF_SEEDS.map((seed) => ({
  id: seed.id,
  type: "gif" as const,
  title: seed.title,
  url: giphyUrl(seed.giphyId, "giphy"),
  previewUrl: giphyUrl(seed.giphyId, "200w"),
  tags: seed.tags,
}));

export function searchChatGifs(
  query: string,
  moodTag: string | null = null,
): ChatGifOption[] {
  const q = query.trim().toLowerCase();
  return CHAT_GIF_CATALOG.filter((gif) => {
    if (moodTag && !gif.tags.includes(moodTag)) return false;
    if (!q) return true;
    const hay = `${gif.title} ${gif.tags.join(" ")}`.toLowerCase();
    return hay.includes(q);
  });
}

export function searchEmojis(query: string, categoryId: string): string[] {
  const category =
    CHAT_EMOJI_CATEGORIES.find((c) => c.id === categoryId) ??
    CHAT_EMOJI_CATEGORIES[0];
  const pool = category?.emojis ?? [];
  const q = query.trim().toLowerCase();
  if (!q) return pool;
  // Unicode emoji search is limited without a name map — filter by including
  // characters from the query when people paste an emoji, else return pool.
  if ([...q].some((ch) => /\p{Extended_Pictographic}/u.test(ch))) {
    return pool.filter((emoji) => emoji.includes(q));
  }
  return pool;
}

export function formatFileSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
